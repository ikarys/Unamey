//! Pack: one generation -> a drop-in skill directory for a project (SKILL.md + reference.html), with an in-memory zip download.
//! This is what gets handed to a model when building a real app: a page to imitate plus its tokens and rules.
//! A concept pack bundles the identity's SKILL.md + reference.html with one HTML per page under `pages/`.

use crate::config::Config;
use crate::db::{self, es};
use crate::pipeline::tokens;
use crate::sql::args;
use serde_json::{Value, json};
use std::path::PathBuf;
use uuid::Uuid;

/// A pack in memory: where it goes under `packs_dir`, its download name, SKILL.md and the files (path relative to the pack root, bytes).
pub struct Pack {
    pub rel: PathBuf,
    pub name: String,
    pub skill_md: String,
    pub files: Vec<(String, Vec<u8>)>,
    pub pages: Option<usize>,
}

fn s(v: &Value) -> &str {
    v.as_str().unwrap_or("")
}

fn list(v: &Value) -> String {
    match v {
        Value::Array(a) => a.iter().filter_map(Value::as_str).collect::<Vec<_>>().join(", "),
        Value::String(x) => x.clone(),
        _ => String::new(),
    }
}

fn bullets(v: &Value) -> String {
    v.as_array().map_or(String::new(), |a| a.iter().filter_map(Value::as_str).map(|x| format!("- {x}\n")).collect())
}

/// `My Dashboard · A` -> `my-dashboard-a`; empty -> `screen`.
pub fn slug(label: &str) -> String {
    let mut out = String::new();
    for c in label.to_lowercase().chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c);
        } else if !out.ends_with('-') && !out.is_empty() {
            out.push('-');
        }
    }
    let out: String = out.trim_matches('-').chars().take(40).collect();
    if out.is_empty() { "screen".into() } else { out.trim_matches('-').to_string() }
}

/// The SKILL.md of a pack, from the generation's brief and notes (direction, archetype, identity).
pub fn skill_md(id: Uuid, brief: &Value, notes: &Value, created_at: &str) -> String {
    let d = &notes["direction"];
    let a = &d["archetype"];
    let i = &d["identity"];
    let name = slug(s(&d["label"]));
    let tokens = [
        ("theme", s(&i["theme"]).to_string()),
        ("canvas", s(&i["canvas"]).to_string()),
        ("surface", s(&i["surface"]).to_string()),
        ("border", s(&i["border"]).to_string()),
        ("text", s(&i["text"]).to_string()),
        ("muted", s(&i["muted"]).to_string()),
        ("accent", s(&i["accent"]).to_string()),
        ("accent2", s(&i["accent2"]).to_string()),
        ("font", format!("{} (Google Fonts)", s(&i["font"]))),
        ("mono", s(&i["mono"]).to_string()),
        ("radius", format!("{}px", i["radius"])),
        ("density", s(&i["density"]).to_string()),
        ("tone", s(&i["tone"]).to_string()),
        ("decoration", s(&i["decoration"]).to_string()),
    ];
    let table: String = tokens
        .iter()
        .filter(|(_, v)| !v.is_empty() && v != "px" && v != " (Google Fonts)")
        .map(|(k, v)| format!("| {k} | {v} |\n"))
        .collect();
    let mobile_note =
        if brief["target"].as_str() == Some("mobile") { "\n`reference.html` is the mobile page (390px wide phone viewport)." } else { "" };
    // The product description the user typed comes first; the screen brief is the reference screen's own request.
    let brief_text = match s(&brief["description"]).trim() {
        "" => s(&brief["brief"]).to_string(),
        desc => format!("{desc}\n\nReference screen: {}", s(&brief["brief"])),
    };
    let mobile = brief["target"].as_str() == Some("mobile");
    let shell_structure = match (d["structure"]["name"].as_str(), d["structure"]["regions"].as_str()) {
        (Some(name), Some(regions)) if mobile => {
            format!(
                "\n\nReference structure: **{name}.** {regions} On the phone these regions stack in one column, in the order `reference.html` shows."
            )
        }
        (Some(name), Some(regions)) => format!("\n\nReference structure: **{name}.** {regions}"),
        _ => String::new(),
    };
    // The generator describes the chrome it actually built; older generations fall back to a generic line.
    let shell = match s(&notes["shell"]).trim() {
        "" => "The chrome of `reference.html` (whatever wraps the content: rails, bars, tab bars) is the product shell.".to_string(),
        shell => format!("The shell of `reference.html`: {}.", shell.trim_end_matches(['.', ' '])),
    };
    format!(
        "---
name: ui-pack-{name}
description: Visual direction, design tokens and a reference page for this project's UI. Use when building or changing any screen, component or style.
---

# UI pack: {label}

Generated by Unamey (generation #{id}, {created_at}). `reference.html` next to this file is the page to imitate: open it before writing any UI and match its look, spacing, type scale and component anatomy. Build with the project's own stack; translate the reference, do not copy the file.{mobile_note}

## Brief

{brief}

Users: {users}
Data objects: {objects}

## Direction

**Archetype: {arch}.** {feel}

{direction}

Structure: {structure}

## Shell

{shell} Keep it on every screen with the active item marked; only the content region changes from page to page.{shell_structure}

## Tokens

| Token | Value |
|---|---|
{table}
`tokens.css` next to this file holds them as CSS variables. Put these in the project's CSS variables or Tailwind theme and use nothing else for colours, fonts and radii. Neutrals: {neutrals}
Where the direction text and this table disagree (tokens can be edited after the direction was written), the table and `tokens.css` win.

## Do

{do}
## Don't

{dont}- No indigo/violet accents, no white + slate neutrals, no Inter or Roboto: that is the generic look this pack exists to avoid.

## How to use

- Copy this directory into the project as `.claude/skills/ui-pack/` (or paste this file into `CLAUDE.md`).
- Before each screen: read `reference.html`, keep the tokens, follow the do / don't lists, then design the screen's own structure from its data.
",
        label = s(&d["label"]),
        brief = brief_text,
        shell = shell,
        shell_structure = shell_structure,
        users = list(&brief["users"]),
        objects = list(&brief["data_objects"]),
        arch = s(&a["name"]),
        feel = s(&a["feel"]),
        direction = s(&d["direction"]),
        structure = s(&a["structure"]),
        neutrals = s(&a["neutrals"]),
        do = bullets(&a["do"]),
        dont = bullets(&a["dont"]),
    )
}

/// The first 8 hex digits of an id: enough to tell pack folders apart.
fn short(id: Uuid) -> String {
    id.simple().to_string()[..8].to_string()
}

/// Builds a generation pack in memory (no disk writes).
pub fn generation(cfg: &Config, id: Uuid) -> Result<Pack, String> {
    let sql = "SELECT g.brief_json, g.notes_json, g.html, to_char(g.created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'), p.name, g.owner_id FROM generations g LEFT JOIN projects p ON p.id = g.project_id WHERE g.id = $1";
    let row = cfg.block(cfg.pool.fetch_optional(sql, args![id])).map_err(es)?.ok_or_else(|| format!("no generation #{id}"))?;
    let (brief, notes, html, created_at, project, owner) = (
        row.get::<Value, _>(0),
        row.get::<Option<Value>, _>(1),
        row.get::<Option<String>, _>(2),
        row.get::<String, _>(3),
        row.get::<Option<String>, _>(4),
        row.get::<Uuid, _>(5),
    );
    let html = html.filter(|h| !h.is_empty()).ok_or("generation has no HTML")?;
    let notes = notes.unwrap_or_default();
    let md = skill_md(id, &brief, &notes, &created_at);
    let id = short(id);
    let rel = match project {
        Some(name) => PathBuf::from(slug(&name)).join(format!("{id}-{}", slug(s(&notes["direction"]["label"])))),
        None => PathBuf::from(format!("{id}-{}", slug(s(&notes["direction"]["label"])))),
    };
    let name = rel.file_name().and_then(|n| n.to_str()).map(|n| n.to_string()).ok_or("pack path has no name")?;
    // One directory per owner: two users' projects with the same name never write over each other.
    let rel = PathBuf::from(owner.to_string()).join(rel);
    let files = vec![
        ("SKILL.md".to_string(), md.as_bytes().to_vec()),
        ("tokens.css".to_string(), (tokens::css(&notes["direction"]["identity"]) + &tokens::status_css(&html)).into_bytes()),
        ("reference.html".to_string(), html.into_bytes()),
    ];
    Ok(Pack { rel, name, skill_md: md, files, pages: None })
}

/// Builds a concept pack in memory (no disk writes).
pub fn concept(cfg: &Config, concept: Uuid) -> Result<Pack, String> {
    let row = cfg
        .block(cfg.pool.fetch_optional(
            "SELECT p.name || '-' || c.name, p.owner_id FROM concepts c JOIN projects p ON p.id = c.project_id WHERE c.id = $1",
            args![concept],
        ))
        .map_err(es)?
        .ok_or_else(|| format!("no concept #{concept}"))?;
    let (name, owner) = (row.get::<String, _>(0), row.get::<Uuid, _>(1));
    let identity = cfg.block(db::identity(cfg, concept))?.ok_or("the concept has no identity yet: pick a generation first")?;
    let html = identity["html"].as_str().filter(|h| !h.is_empty()).ok_or("the identity generation has no HTML")?;
    let id: Uuid = serde_json::from_value(identity["id"].clone()).map_err(es)?;
    let pages = cfg.block(db::concept_pages(cfg, concept))?;

    let has_mobile = pages.iter().any(|(_, target, _, _, _)| target == "mobile");
    let mut md = skill_md(id, &identity["request"], &identity["notes"], s(&identity["created_at"]));
    md += "\n## Pages\n\n";
    if has_mobile {
        md += "Mobile pages (`*.mobile.html`) are 390px phone versions of the same identity.\n\n";
    }
    md += &format!("- `reference.html`: the identity page (generation #{id})\n");
    let file_name = |page: &str, target: &str| {
        if target == "mobile" { format!("{}.mobile.html", slug(page)) } else { format!("{}.html", slug(page)) }
    };
    for (page, target, pid, _, pbrief) in &pages {
        let name = file_name(page, target);
        if target == "mobile" {
            md += &format!("- `pages/{name}`: {page}, mobile (generation #{pid})\n");
        } else {
            md += &format!("- `pages/{name}`: {page} (generation #{pid})\n");
        }
        if !pbrief.trim().is_empty() {
            md += &format!("  Brief: {}\n", pbrief.trim().replace('\n', "\n  "));
        }
    }
    let rel = PathBuf::from(slug(&name));
    let pack_name = rel.to_str().map(|s| s.to_string()).ok_or("concept slug is not valid UTF-8")?;
    let rel = PathBuf::from(owner.to_string()).join(rel);
    let mut files = vec![
        ("SKILL.md".to_string(), md.as_bytes().to_vec()),
        ("tokens.css".to_string(), (tokens::css(&identity["notes"]["direction"]["identity"]) + &tokens::status_css(html)).into_bytes()),
        ("reference.html".to_string(), html.as_bytes().to_vec()),
    ];
    for (page, target, _, h, _) in &pages {
        files.push((format!("pages/{}", file_name(page, target)), h.as_bytes().to_vec()));
    }
    Ok(Pack { rel, name: pack_name, skill_md: md, files, pages: Some(pages.len()) })
}

/// Writes a pack to disk under `packs_dir`.
fn write_dir(cfg: &Config, p: &Pack) -> Result<Value, String> {
    let root = cfg.packs_dir.join(&p.rel);
    std::fs::create_dir_all(&root).map_err(es)?;
    for (path, bytes) in &p.files {
        let file = root.join(path);
        if let Some(parent) = file.parent() {
            std::fs::create_dir_all(parent).map_err(es)?;
        }
        std::fs::write(&file, bytes).map_err(es)?;
    }
    let dir = root.canonicalize().map_err(es)?;
    let mut out = json!({"dir": dir.display().to_string(), "skill_md": p.skill_md.clone()});
    if let Some(pages) = p.pages {
        out["pages"] = json!(pages);
    }
    Ok(out)
}

/// Writes `<packs_dir>[/<project>]/<id>-<slug>/{SKILL.md, reference.html}`; returns `{dir, skill_md}`.
pub fn write(cfg: &Config, id: Uuid) -> Result<Value, String> {
    write_dir(cfg, &generation(cfg, id)?)
}

/// Writes `<packs_dir>/<project-concept-slug>/{SKILL.md, reference.html, pages/<page-slug>.html}` from the concept's identity and pages; returns `{dir, skill_md, pages}`.
pub fn write_concept(cfg: &Config, concept: Uuid) -> Result<Value, String> {
    write_dir(cfg, &self::concept(cfg, concept)?)
}

/// Builds a zip of the pack in memory, with every entry under `ui-pack/`.
pub fn zip(p: &Pack) -> Result<Vec<u8>, String> {
    let mut w = zip::ZipWriter::new(std::io::Cursor::new(Vec::new()));
    let opts = zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);
    for (path, bytes) in &p.files {
        w.start_file(format!("ui-pack/{path}"), opts).map_err(es)?;
        std::io::Write::write_all(&mut w, bytes).map_err(es)?;
    }
    Ok(w.finish().map_err(es)?.into_inner())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn slugs() {
        assert_eq!(slug("A · Dense ops console"), "a-dense-ops-console");
        assert_eq!(slug(""), "screen");
        assert_eq!(slug("---"), "screen");
    }

    #[test]
    fn skill_md_has_the_parts() {
        let brief = json!({
            "brief": "Fleet dashboard",
            "description": "A fleet tool for dispatchers.",
            "users": "dispatchers",
            "data_objects": ["trucks", "routes"],
        });
        let notes = json!({"shell": "A 48px top bar with the brand, then a bottom tab bar: Home, Play, Tournaments, Profile.", "direction": {"label": "A · Terminal fleet", "direction": "Stacked panes.",
                "structure": {"name": "Master list + detail", "regions": "List left, detail right."}, "archetype": {"name": "Terminal", "feel": "TUI.", "structure": "Panes.", "neutrals": "dark", "do": ["mono"], "dont": ["cards"]},
                           "identity": {"theme": "dark", "canvas": "#0b0e0c", "accent": "#3ddc84", "font": "JetBrains Mono", "radius": 2, "density": "compact"}}});
        let md = skill_md(uuid::Uuid::from_u128(7), &brief, &notes, "2026-11-04");
        for part in [
            "name: ui-pack-a-terminal-fleet",
            "A fleet tool for dispatchers.\n\nReference screen: Fleet dashboard",
            "## Shell\n\nThe shell of `reference.html`: A 48px top bar with the brand, then a bottom tab bar: Home, Play, Tournaments, Profile. Keep it",
            "Reference structure: **Master list + detail.** List left, detail right.",
            "the table and `tokens.css` win",
            "trucks, routes",
            "**Archetype: Terminal.**",
            "| canvas | #0b0e0c |",
            "| radius | 2px |",
            "- mono\n",
            "- cards\n",
            "reference.html",
        ] {
            assert!(md.contains(part), "missing {part:?}\n{md}");
        }
        assert!(!md.contains("| surface |"), "empty tokens are skipped");
    }

    #[test]
    fn skill_md_without_description_or_structure() {
        let brief = json!({"brief": "Fleet dashboard"});
        let notes = json!({"direction": {"label": "A", "archetype": {}, "identity": {}}});
        let md = skill_md(uuid::Uuid::from_u128(7), &brief, &notes, "2026-11-04");
        assert!(md.contains("## Brief\n\nFleet dashboard\n"), "{md}");
        assert!(!md.contains("Reference screen:"));
        assert!(!md.contains("Reference structure:"));
        assert!(md.contains("## Shell\n\nThe chrome of `reference.html`"));
    }

    #[test]
    fn zip_has_the_files() {
        let p = Pack {
            rel: PathBuf::from("x"),
            name: "x".into(),
            skill_md: "md".into(),
            files: vec![("SKILL.md".to_string(), b"md".to_vec()), ("pages/a.html".to_string(), b"a".to_vec())],
            pages: None,
        };
        let bytes = zip(&p).unwrap();
        let mut archive = zip::ZipArchive::new(std::io::Cursor::new(bytes)).unwrap();
        assert!(archive.by_name("ui-pack/SKILL.md").is_ok());
        assert!(archive.by_name("ui-pack/pages/a.html").is_ok());
    }

    #[test]
    fn skill_md_shell_gets_a_period_and_mobile_stacks() {
        let notes = json!({
            "shell": "A top bar then a bottom tab bar",
            "direction": {
                "label": "A",
                "structure": {"name": "Map + list", "regions": "A map above, a list on one side."},
                "archetype": {},
                "identity": {}
            }
        });

        let mobile_md = skill_md(uuid::Uuid::from_u128(7), &json!({"brief": "b", "target": "mobile"}), &notes, "2026-11-04");
        assert!(mobile_md.contains("a bottom tab bar. Keep it on every screen"));
        assert!(mobile_md.contains("stack in one column"));

        let desktop_md = skill_md(uuid::Uuid::from_u128(7), &json!({"brief": "b", "target": "desktop"}), &notes, "2026-11-04");
        assert!(!desktop_md.contains("stack in one column"));
    }
}
